    {
        if (preg_match('/^[a-zA-Z0-9\/\+=]*$/', $input)) {
            $decoded = base64_decode($input, true);
            if ($decoded !== false) {
                $jsonData = json_decode($decoded, true);
                if (json_last_error() === JSON_ERROR_NONE) {
                    return true;
